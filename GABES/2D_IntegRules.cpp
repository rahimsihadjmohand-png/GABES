void Element::Construct2DGaussianRule(ITND _2D_Rule[], int N1, int N2)
{
	double Xi[25], Eta[25], W1[25], W2[25];

	Get1DGaussianRule(Xi, W1, N1);
	Get1DGaussianRule(Eta, W2, N2);

	int idx = 0;

	for (int i2 = 0; i2 < N2; i2++)
	{
		for (int i1 = 0; i1 < N1; i1++, idx++)
		{
			_2D_Rule[idx].Xi = Xi[i1];
			_2D_Rule[idx].Eta = Eta[i2];
			_2D_Rule[idx].W = W1[i1] * W2[i2];
		}
	}
}




